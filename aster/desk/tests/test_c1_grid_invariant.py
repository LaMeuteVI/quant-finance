"""Test: BACKLOG invariant — no liquid major may use a high-low / Corwin-Schultz
estimator as its primary spread source in the desk cost grid.

Liquid majors: BTC, ETH, BNB, SOL, XRP (the desk's five-major perp panel).
The grid (research/atlas/cost-grid.csv) is regenerated by
``research/notes/2026-10-20-C1-grid-rebuild.py`` from aggTrades effective
spread data + order-book cross-check; thin alts (LINK, SUI, NEAR, FET, XMR,
AAVE, DOGE) may use the documented ``max(CHL, CS)`` formula but never the
high-low estimator as a *primary* spread source for a liquid major.

This test is the gate: if any of BTC/ETH/BNB/SOL/XRP carries
``spread_source`` in {corwin_schultz, chl, high_low} on any (notional, hour)
row, the C1 invariant is broken and no strategy run is permitted.
"""
from __future__ import annotations

import csv
from pathlib import Path

import pandas as pd

ROOT = Path("/root/quant-finance/aster/desk")
GRID = ROOT / "research/atlas/cost-grid.csv"
LIQUID_MAJORS = ("BTCUSDT", "ETHUSDT", "BNBUSDT", "SOLUSDT", "XRPUSDT")
FORBIDDEN_SOURCES = {"corwin_schultz", "chl", "high_low"}


def test_c1_no_high_low_for_liquid_majors():
    df = pd.read_csv(GRID)
    majors = df[df["symbol"].isin(LIQUID_MAJORS)]
    assert not majors.empty, f"no liquid-major rows found in {GRID}"

    bad = majors[majors["spread_source"].isin(FORBIDDEN_SOURCES)]
    if not bad.empty:
        offenders = (
            bad.groupby(["symbol", "spread_source"]).size().to_dict()
        )
        raise AssertionError(
            "C1 invariant violated: liquid majors use forbidden "
            f"high-low/Corwin-Schultz estimator as primary spread source. "
            f"Offenders: {offenders}.  Re-run "
            f"research/notes/2026-10-20-C1-grid-rebuild.py and check "
            f"effective-spread.csv."
        )


def test_c1_grid_has_all_liquid_majors():
    df = pd.read_csv(GRID)
    have = set(df["symbol"].unique())
    missing = set(LIQUID_MAJORS) - have
    assert not missing, f"liquid majors missing from grid: {missing}"


def test_c1_grid_round_trip_btc_at_100k_is_below_old():
    """Sanity: BTC round-trip at 100k at hour 0 must drop from ~42 bps
    (Corwin-Schultz v1) to ~22 bps with the aggTrades proxy."""
    df = pd.read_csv(GRID)
    row = df[(df["symbol"] == "BTCUSDT")
             & (df["notional"] == 100_000)
             & (df["utc_hour"] == 0)]
    assert len(row) == 1
    rt = float(row["round_trip_bps"].iloc[0])
    assert rt < 30.0, (
        f"BTC 100k round-trip at hour 0 = {rt:.2f} bps; expected <30 bps. "
        "The aggTrades proxy should land near 22 bps."
    )


def test_c1_grid_hash_recorded_in_costs_md():
    """costs.md must record the SHA-256 of the regenerated grid."""
    import hashlib, re
    text = (ROOT / "research/atlas/costs.md").read_text(encoding="utf-8")
    m = re.search(r"cost-grid\.csv` \(nouveau\)[^\`]*SHA-256 `([0-9a-f]+)`", text)
    assert m, "costs.md missing SHA-256 of new cost-grid.csv"
    recorded = m.group(1)
    actual = hashlib.sha256(GRID.read_bytes()).hexdigest()
    assert recorded == actual, (
        f"costs.md SHA mismatch: recorded {recorded[:16]}… "
        f"vs actual {actual[:16]}…"
    )